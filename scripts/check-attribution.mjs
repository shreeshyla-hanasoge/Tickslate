// Fails when a commit message or PR body carries AI attribution. Only messages
// are scanned, never files, so the docs and tests that discuss the rule are safe.
// Uses node:* only, so CI runs it with no install.
//
// Usage: node scripts/check-attribution.mjs [base] [head] [--body-file <path>] [--self-test]
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const TOOLS = 'claude|chatgpt|codex|copilot|gemini|gpt|openai|anthropic|cursor|windsurf|devin|aider|\\bai\\b|llm|assistant'

// Trailers and footers are matched where they start a line (after quoting or
// list markers), so a sentence that only mentions "Co-Authored-By" is allowed.
// The identifiers and the robot emoji are never legitimate, so they match anywhere.
const RULES = [
  { name: 'Co-Authored-By trailer', re: /^[\s>*_-]*co-authored-by\s*:/i },
  { name: 'Generated with/by footer', re: new RegExp(`^[^a-z0-9]*generated\\s+(with|by)\\b.*(${TOOLS})`, 'i') },
  { name: 'robot emoji', re: /\u{1F916}/u },
  { name: 'anthropic noreply address', re: /noreply@anthropic\.com/i },
  { name: 'claude-code URL', re: /claude\.com\/claude-code/i },
]

export function scanMessage(text) {
  const hits = []
  text.split(/\r?\n/).forEach((line, i) => {
    for (const rule of RULES) {
      if (rule.re.test(line)) hits.push({ line: i + 1, text: line.trim(), rule: rule.name })
    }
  })
  return hits
}

const runGit = (args) => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 1 << 26 })

export function scanCommits(base, head, git = runGit) {
  // %x00 ends each message so multi-line bodies split cleanly.
  const out = git(['log', '--format=%H%n%B%x00', `${base}..${head}`])
  const found = []
  for (const chunk of out.split('\0')) {
    const trimmed = chunk.replace(/^\n+/, '')
    if (!trimmed) continue
    const nl = trimmed.indexOf('\n')
    const hash = nl === -1 ? trimmed : trimmed.slice(0, nl)
    const body = nl === -1 ? '' : trimmed.slice(nl + 1)
    for (const h of scanMessage(body)) found.push({ where: `commit ${hash}`, ...h })
  }
  return found
}

// [text, shouldMatch]
const FIXTURES = [
  ['Co-Authored-By: Claude Sonnet <noreply@anthropic.com>', true],
  ['co-authored-by: Anyone <a@b.c>', true],
  ['Generated with [Claude Code](https://claude.com/claude-code)', true],
  ['Generated by ChatGPT', true],
  ['\u{1F916} Generated with Codex', true],
  ['made with \u{1F916}', true],
  ['see noreply@anthropic.com', true],
  ['> Co-Authored-By: x', true],
  ['No Co-Authored-By lines are allowed', false],
  ['Add a guard for the Generated with footer rule', false],
  ['Generated by the build script', false],
  ['Fix the grid focus ring', false],
]

export function selfTest() {
  return FIXTURES.filter(([t, want]) => (scanMessage(t).length > 0) !== want).map(([t]) => t)
}

function main(argv) {
  const args = []
  let bodyFile = null
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--self-test') {
      const bad = selfTest()
      if (bad.length) {
        console.error(`self-test failed for:\n${bad.join('\n')}`)
        return 1
      }
      console.log(`self-test ok (${FIXTURES.length} fixtures)`)
      return 0
    }
    if (argv[i] === '--body-file') bodyFile = argv[++i]
    else args.push(argv[i])
  }
  const [base = 'origin/master', head = 'HEAD'] = args
  const found = scanCommits(base, head)
  if (bodyFile) for (const h of scanMessage(readFileSync(bodyFile, 'utf8'))) found.push({ where: 'PR body', ...h })
  if (!found.length) {
    console.log(`No AI attribution in ${base}..${head}.`)
    return 0
  }
  for (const f of found) console.error(`${f.where}, line ${f.line}: ${f.rule}: ${f.text}`)
  console.error('\nCommits and PRs are authored by the maintainer alone. Remove the line (amend or rebase) and push again.')
  return 1
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)))
